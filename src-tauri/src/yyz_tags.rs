/// 全名精确索引：席位 -> 名号（同一席位命中多个名号时按库中顺序保留）。
fn exact_map() -> &'static HashMap<&'static str, Vec<&'static str>> {
    static MAP: OnceLock<HashMap<&'static str, Vec<&'static str>>> = OnceLock::new();
    MAP.get_or_init(|| {
        let mut map: HashMap<&'static str, Vec<&'static str>> = HashMap::new();
        for (tag, seats) in YYZ_TAGS {
            for seat in *seats {
                let tags = map.entry(*seat).or_default();
                if !tags.contains(tag) {
                    tags.push(*tag);
                }
            }
        }
        map
    })
}

/// 归一化索引：去掉公司后缀 / “证券营业部” / 分公司 / 括号 / 空白后的席位 -> 名号。
fn norm_map() -> &'static HashMap<String, Vec<&'static str>> {
    static MAP: OnceLock<HashMap<String, Vec<&'static str>>> = OnceLock::new();
    MAP.get_or_init(|| {
        let mut map: HashMap<String, Vec<&'static str>> = HashMap::new();
        for (tag, seats) in YYZ_TAGS {
            for seat in *seats {
                let tags = map.entry(norm_seat_name(seat)).or_default();
                if !tags.contains(tag) {
                    tags.push(*tag);
                }
            }
        }
        map
    })
}

/// 去掉席位全名里的冗余后缀与空白，用于容错匹配。
pub fn norm_seat_name(name: &str) -> String {
    let mut s = name.trim().to_string();
    for pat in [
        "股份有限公司",
        "有限责任公司",
        "有限公司",
        "证券营业部",
        "营业部",
        "分公司",
    ] {
        s = s.replace(pat, "");
    }
    s.retain(|c| !c.is_whitespace() && !matches!(c, '（' | '）' | '(' | ')'));
    s
}

/// 席位全名 -> 游资名号：先精确匹配，未命中再按归一化名匹配。
pub fn tags_for(name: &str) -> Vec<&'static str> {
    let trimmed = name.trim();
    if let Some(tags) = exact_map().get(trimmed) {
        return tags.clone();
    }
    let norm = norm_seat_name(trimmed);
    if norm.is_empty() {
        return Vec::new();
    }
    norm_map().get(&norm).cloned().unwrap_or_default()
}

